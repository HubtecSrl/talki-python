"""Regenerate the `talki` package from the OpenAPI document.

Most of `talki/` is generated by openapi-python-client (pinned in the `codegen`
dependency group) from `openapi/talki-v1.yaml`, with the templates in
`codegen/templates/`. The modules in HAND_WRITTEN are not: they are kept as
they are and copied into every build.

    uv run scripts/generate.py                       # rewrite talki/
    uv run scripts/generate.py --check               # fail if talki/ is stale
    uv run scripts/generate.py --spec S --out DIR    # build a full package elsewhere

`--out` is how another project builds the client for a spec this repo has not
pulled yet: the package lands in DIR/talki, and this checkout is left alone.
"""

from __future__ import annotations

import argparse
import filecmp
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "talki"
SPEC = ROOT / "openapi" / "talki-v1.yaml"

HAND_WRITTEN = frozenset(
    {
        "_resource.py",
        "_talki.py",
        "_transport.py",
        "_version.py",
        "exceptions.py",
        "oauth.py",
        "pagination.py",
        "py.typed",
        "webhooks.py",
    }
)
# Left behind by running or checking the package in place; never generated.
IGNORED = ["__pycache__", ".mypy_cache", ".ruff_cache", ".pytest_cache"]


def _tool(name: str) -> str:
    """A console script from this interpreter's environment, where `uv run` put the pins."""
    found = shutil.which(name, path=str(Path(sys.executable).parent))
    if found is None:
        sys.exit(f"{name} is not installed here: run this with `uv run` from the repository")
    return found


def build(spec: Path, into: Path) -> Path:
    """The full package, generated from ``spec`` plus the hand-written modules, at ``into/talki``."""
    package = into / "talki"
    subprocess.run(
        [
            _tool("openapi-python-client"),
            "generate",
            "--path",
            str(spec),
            "--output-path",
            str(package),
            "--meta",
            "none",
            "--config",
            str(ROOT / "codegen" / "config.yaml"),
            "--custom-template-path",
            str(ROOT / "codegen" / "templates"),
            "--fail-on-warning",
        ],
        check=True,
        stdout=subprocess.DEVNULL,
    )
    config = ["--config", str(ROOT / "pyproject.toml"), "--no-cache"]
    subprocess.run([_tool("ruff"), "check", "--fix-only", "--quiet", *config, str(package)], check=True)
    subprocess.run([_tool("ruff"), "format", "--quiet", *config, str(package)], check=True)
    for name in sorted(HAND_WRITTEN):
        if (package / name).exists():
            sys.exit(f"the generator now writes talki/{name}, which is hand-written here")
        shutil.copy2(PACKAGE / name, package / name)
    return package


def _differences(left: Path, right: Path) -> list[str]:
    """Paths under talki/ that differ between the two trees, by content."""

    def walk(compared: filecmp.dircmp[str], prefix: str) -> list[str]:
        found = [f"{prefix}{name}" for name in compared.left_only + compared.right_only + compared.common_funny]
        _, mismatch, errors = filecmp.cmpfiles(compared.left, compared.right, compared.common_files, shallow=False)
        found += [f"{prefix}{name}" for name in mismatch + errors]
        for name, sub in sorted(compared.subdirs.items()):
            found += walk(sub, f"{prefix}{name}/")
        return found

    return sorted(walk(filecmp.dircmp(left, right, ignore=IGNORED), "talki/"))


def _replace(target: Path, built: Path) -> None:
    """``target`` becomes ``built``, renamed into place beside it, so a failure never leaves it half-written."""
    staged = target.with_name(f".{target.name}-new")
    shutil.rmtree(staged, ignore_errors=True)
    shutil.copytree(built, staged)
    if target.exists():
        shutil.rmtree(target)
    staged.rename(target)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--spec", type=Path, default=SPEC, help="the OpenAPI document (default: %(default)s)")
    parser.add_argument("--out", type=Path, help="build the package into OUT/talki instead of rewriting talki/")
    parser.add_argument("--check", action="store_true", help="fail if talki/ is not what the spec generates")
    args = parser.parse_args()

    if args.out:
        target = args.out.resolve() / "talki"
        if target == PACKAGE or target.is_relative_to(PACKAGE) or PACKAGE.is_relative_to(target):
            sys.exit("--out must not be this checkout: run without --out to regenerate talki/ here")
        with tempfile.TemporaryDirectory() as tmp:
            built = build(args.spec.resolve(), Path(tmp))
            target.parent.mkdir(parents=True, exist_ok=True)
            _replace(target, built)
        print(target)
        return

    with tempfile.TemporaryDirectory() as tmp:
        built = build(args.spec.resolve(), Path(tmp))
        stale = _differences(PACKAGE, built)
        if args.check:
            if stale:
                print("\n".join(stale))
                sys.exit("talki/ is not what the spec generates: run `uv run scripts/generate.py` and commit it")
            return
        if not stale:
            print("talki/ is up to date")
            return
        _replace(PACKAGE, built)
        print(f"talki/ regenerated ({len(stale)} paths changed)")


if __name__ == "__main__":
    main()
